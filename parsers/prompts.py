def format_excel_for_ai(df) -> str:
    """
    Форматирует DataFrame в текстовый формат для AI
    
    Args:
        df: pandas DataFrame с данными Excel
        
    Returns:
        str: Текстовое представление таблицы
    """
    # Преобразуем DataFrame в табличный вид
    result = []
    
    for idx, row in df.iterrows():
        # Фильтруем пустые значения
        row_values = [str(val) if val is not None and str(val) != 'nan' else '' for val in row]
        
        # Убираем строки, где все пустые
        if any(val for val in row_values):
            result.append(f"Строка {idx + 1}: " + " | ".join(row_values))
    
    return "\n".join(result)
